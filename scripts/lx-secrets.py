def _parse_inventory_group(hosts_ini: Path, group: str) -> list[str]:
    """Return hostnames in a given group from a plain INI-format inventory."""
    hostnames: list[str] = []
    in_group = False
    with hosts_ini.open() as fh:
        for raw_line in fh:
            line = raw_line.strip()
            if line == f"[{group}]":
                in_group = True
                continue
            if in_group:
                if line.startswith("["):
                    break
                if line and not line.startswith(";") and not line.startswith("#"):
                    hostnames.append(line.split()[0])
    return hostnames


