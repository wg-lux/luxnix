def build_parser() -> argparse.ArgumentParser:
    root = argparse.ArgumentParser(
        prog="lx-secrets",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    root.add_argument(
        "--stick",
        metavar="PATH",
        help=f"Override stick path (also set via {ENV_VAR})",
    )

    sub = root.add_subparsers(dest="command", metavar="COMMAND", required=True)

    # ---- stick ----
    stick_cmd = sub.add_parser("stick", help="Stick lifecycle operations")
    stick_sub = stick_cmd.add_subparsers(dest="subcommand", metavar="SUBCOMMAND", required=True)

    stick_sub.add_parser("check", help="Verify stick is present and valid")

    init_p = stick_sub.add_parser("init", help="Initialise directory layout on a new stick")
    init_p.add_argument("--force", action="store_true", help="Reinitialise even if already set up")
    init_p.add_argument(
        "--mode", choices=["admin", "user"], default="admin",
        help="Stick mode: 'admin' for full network management, 'user' for personal use (default: admin)"
    )
    init_p.add_argument(
        "--owner", metavar="USERNAME",
        help="Username for user-mode sticks (required when --mode user)"
    )

    stick_sub.add_parser("backup", help="Create a backup archive on the stick")

    # ---- identity ----
    id_cmd = sub.add_parser("identity", help="SSH identity management")
    id_sub = id_cmd.add_subparsers(dest="subcommand", metavar="SUBCOMMAND", required=True)

    id_sub.add_parser("list", help="List all identities on the stick")

    gen_user = id_sub.add_parser("gen-user", help="Generate a user SSH key-pair")
    gen_user.add_argument("username", help="Username")
    gen_user.add_argument(
        "--key-type", dest="key_type", default="ed25519",
        choices=["ed25519", "rsa"], help="Key algorithm (default: ed25519)"
    )
    gen_user.add_argument("--force", action="store_true", help="Overwrite existing key")

    gen_host = id_sub.add_parser("gen-host", help="Generate a host SSH key-pair (admin only)")
    gen_host.add_argument("hostname", help="Hostname")
    gen_host.add_argument(
        "--key-type", dest="key_type", default="ed25519",
        choices=["ed25519", "rsa"], help="Key algorithm (default: ed25519)"
    )
    gen_host.add_argument("--force", action="store_true", help="Overwrite existing key")

    imp_kp = id_sub.add_parser(
        "import-keypair",
        help="Import an existing SSH key pair into the vault",
    )
    imp_kp.add_argument("username", help="Username to import under (e.g. admin, dev_01)")
    imp_kp.add_argument(
        "--private", dest="private_key", required=True, metavar="FILE",
        help="Path to the private key file",
    )
    imp_kp.add_argument(
        "--public", dest="public_key", default=None, metavar="FILE",
        help="Path to the public key file (default: <private>.pub)",
    )
    imp_kp.add_argument(
        "--force", action="store_true",
        help="Overwrite existing key in vault (and local ~/.ssh/ if --deploy-local)",
    )
    imp_kp.add_argument(
        "--deploy-local", action="store_true",
        help="Also install the private key to ~/.ssh/id_<type> on this machine",
    )

    imp_infra = id_sub.add_parser(
        "import-infra-key",
        help="Import an infrastructure SSH key (stored under identities/infra/, NOT synced to inventory)",
    )
    imp_infra.add_argument("name", help="Identifier for the key (e.g. hetzner-main)")
    imp_infra.add_argument(
        "--private", dest="private_key", required=True, metavar="FILE",
        help="Path to the private key file",
    )
    imp_infra.add_argument(
        "--public", dest="public_key", default=None, metavar="FILE",
        help="Path to the public key file (default: <private>.pub)",
    )
    imp_infra.add_argument(
        "--force", action="store_true",
        help="Overwrite existing key in vault and local deploy target",
    )
    imp_infra.add_argument(
        "--deploy-path", dest="deploy_path", default=None, metavar="PATH",
        help="Install the private key at this local path (e.g. ~/.ssh/ssh-hetzner-main_openssh)",
    )

    sync_p = id_sub.add_parser(
        "sync-inventory",
        help="Write pubkeys + password hashes to ansible/inventory/group_vars/stick_pubkeys.yml",
    )
    sync_p.add_argument(
        "--output", default=STICK_PUBKEYS_INVENTORY, metavar="FILE",
        help=f"Output file (default: {STICK_PUBKEYS_INVENTORY})",
    )
    sync_p.add_argument("--no-hashes", action="store_true", help="Omit password hashes from output")
    sync_p.add_argument("--dry-run", action="store_true", help="Print output without writing")

    # ---- user ----
    user_cmd = sub.add_parser(
        "user",
        help="Personal password & identity management (works on both stick modes)",
    )
    user_sub = user_cmd.add_subparsers(dest="subcommand", metavar="SUBCOMMAND", required=True)

    _u_arg = dict(metavar="USERNAME", dest="username", default=None,
                  help="Username (inferred from personal stick owner if omitted)")

    set_pwd = user_sub.add_parser("set-password", help="Set or generate a user password on the stick")
    set_pwd.add_argument("--username", **_u_arg)
    set_pwd.add_argument(
        "--generate", action="store_true",
        help="Generate a random 24-character password instead of prompting"
    )

    show_hash = user_sub.add_parser("show-hash", help="Print the sha512crypt hash (safe to share)")
    show_hash.add_argument("--username", **_u_arg)

    show_pwd = user_sub.add_parser("show-password", help="Print the plaintext password")
    show_pwd.add_argument("--username", **_u_arg)
    show_pwd.add_argument(
        "--confirm", action="store_true",
        help="Required on admin sticks to prevent accidental exposure"
    )

    user_sync = user_sub.add_parser(
        "sync",
        help="Output a YAML snippet (pubkey + hash) for submitting to the admin",
    )
    user_sync.add_argument("--username", **_u_arg)
    user_sync.add_argument(
        "--output", metavar="FILE", default=None,
        help="Write to FILE instead of stdout"
    )

    # ---- admin ----
    admin_cmd = sub.add_parser(
        "admin",
        help="Admin-only operations: import user submissions, manage all users",
    )
    admin_sub = admin_cmd.add_subparsers(dest="subcommand", metavar="SUBCOMMAND", required=True)

    imp_snip = admin_sub.add_parser(
        "import-snippet",
        help="Import a user's submitted YAML snippet (pubkey + hash; no plaintext passwords)",
    )
    imp_snip.add_argument("snippet_file", metavar="SNIPPET_YML", help="Path to the snippet file")

    imp_pub = admin_sub.add_parser("import-pubkey", help="Import a single pubkey for a user")
    imp_pub.add_argument("username", help="Username")
    imp_pub.add_argument("pubkey", help="SSH public key string (e.g. 'ssh-ed25519 AAAA…')")

    admin_sub.add_parser("list-users", help="List all users with their data status")

    # ---- cert ----
    cert_cmd = sub.add_parser("cert", help="Certificate management (admin only)")
    cert_sub = cert_cmd.add_subparsers(dest="subcommand", metavar="SUBCOMMAND", required=True)

    cert_sub.add_parser("list", help="List certificates on the stick")

    imp_ssl = cert_sub.add_parser("import-ssl", help="Import an SSL/TLS certificate")
    imp_ssl.add_argument("domain", help="Domain name (e.g. endo-reg.net)")
    imp_ssl.add_argument("cert", metavar="CERT_PEM", help="Path to fullchain/certificate PEM")
    imp_ssl.add_argument("key", metavar="KEY_PEM", help="Path to private key PEM")

    imp_vpn = cert_sub.add_parser("import-openvpn", help="Import OpenVPN certificate material")
    imp_vpn.add_argument(
        "src_dir", metavar="SRC_DIR",
        help="Directory with ca.pem, crt.crt, key.key, dh.pem, tls.pem (e.g. /etc/openvpn)",
    )

    dep_ssl = cert_sub.add_parser("deploy-ssl", help="Copy SSL cert to a staging directory")
    dep_ssl.add_argument("domain", help="Domain name")
    dep_ssl.add_argument("--dest", default="~/.lxv/deploy/ssl", metavar="DIR")

    dep_vpn = cert_sub.add_parser("deploy-openvpn", help="Copy OpenVPN certs to target directory")
    dep_vpn.add_argument("--dest", default="/etc/openvpn", metavar="DIR")

    # ---- vault ----
    vault_cmd = sub.add_parser(
        "vault",
        help="Integrate stick secrets with the Luxnix vault (~/.lxv/deploy/)",
    )
    vault_sub = vault_cmd.add_subparsers(dest="subcommand", metavar="SUBCOMMAND", required=True)

    _vault_dir_arg = dict(
        metavar="DIR", default="~/.lxv", dest="vault_dir",
        help="Vault root directory (default: ~/.lxv)",
    )

    stage_ssl = vault_sub.add_parser(
        "stage-ssl", help="Stage SSL cert from stick into ~/.lxv/deploy/<hostname>/",
    )
    stage_ssl.add_argument("domain")
    stage_ssl.add_argument("hostname")
    stage_ssl.add_argument("--vault-dir", **_vault_dir_arg)

    stage_ssl_grp = vault_sub.add_parser(
        "stage-ssl-group", help="Stage SSL cert for all hosts in an inventory group",
    )
    stage_ssl_grp.add_argument("domain")
    stage_ssl_grp.add_argument("group", help="Ansible inventory group (e.g. ssl_cert)")
    stage_ssl_grp.add_argument("--vault-dir", **_vault_dir_arg)
    stage_ssl_grp.add_argument(
        "--hosts-ini", default="ansible/inventory/hosts.ini", metavar="FILE",
    )

    stage_pwds = vault_sub.add_parser(
        "stage-passwords",
        help="Write admin-passwords.yml from stick (admin only; delete after use)",
    )
    stage_pwds.add_argument(
        "--output", default="/tmp/lx-admin-passwords.yml", metavar="FILE",
        help="Output path (default: /tmp/lx-admin-passwords.yml)",
    )
    stage_pwds.add_argument(
        "--username", metavar="USERNAME", default=None,
        help="Limit to a single user",
    )

    stage_kc = vault_sub.add_parser(
        "stage-keycloak-admin",
        help="Stage the keycloak_admin password for a host (vault-encrypted, never in Nix store)",
    )
    stage_kc.add_argument("--hostname", required=True, help="Target hostname (e.g. h-01)")
    stage_kc.add_argument("--vault-dir", **_vault_dir_arg)

    vault_status = vault_sub.add_parser("status", help="Show staged secrets per hostname")
    vault_status.add_argument("hostname", nargs="?", default=None)
    vault_status.add_argument("--vault-dir", **_vault_dir_arg)

    return root


