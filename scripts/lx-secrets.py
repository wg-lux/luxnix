def _secure_copy(src: Path, dst: Path, mode: int = stat.S_IRUSR | stat.S_IWUSR) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    os.chmod(dst, mode)


def _read_meta(stick: Path) -> dict:
    return yaml.safe_load((stick / STICK_META_FILENAME).read_text()) or {}


def _write_meta(stick: Path, meta: dict) -> None:
    meta_file = stick / STICK_META_FILENAME
    meta_file.write_text(yaml.dump(meta, default_flow_style=False))
    os.chmod(meta_file, stat.S_IRUSR | stat.S_IWUSR)


def _stick_mode(stick: Path) -> str:
    """Return 'admin' or 'user'."""
    return _read_meta(stick).get("mode", "admin")


def _stick_owner(stick: Path) -> Optional[str]:
    """For user-mode sticks: the username this stick belongs to."""
    return _read_meta(stick).get("owner")


def _require_admin_stick(stick: Path) -> None:
    if _stick_mode(stick) == "user":
        owner = _stick_owner(stick) or "?"
        print(
            f"[error] This is a personal stick (owner: {owner}).\n"
            f"  This command requires an admin stick.",
            file=sys.stderr,
        )
        sys.exit(1)


# ---------------------------------------------------------------------------
# Password utilities
# ---------------------------------------------------------------------------

_PASSWORD_ALPHABET = string.ascii_letters + string.digits + "!@#%^&*-_"


def _generate_secure_password(length: int = 24) -> str:
    """Generate a cryptographically random password."""
    return "".join(_secrets.choice(_PASSWORD_ALPHABET) for _ in range(length))


def _hash_password(password: str) -> str:
    """Generate a SHA-512 crypt hash (NixOS hashedPassword format)."""
    result = subprocess.run(
        ["openssl", "passwd", "-6", "-stdin"],
        input=password,
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout.strip()


def _user_secrets_dir(stick: Path, username: str) -> Path:
    return stick / "identities" / "users" / username / "secrets"


def _get_user_password(stick: Path, username: str) -> Optional[str]:
    p = _user_secrets_dir(stick, username) / "password"
    return p.read_text().strip() if p.exists() else None


def _get_user_hash(stick: Path, username: str) -> Optional[str]:
    p = _user_secrets_dir(stick, username) / "password.hash"
    return p.read_text().strip() if p.exists() else None


def _store_password(stick: Path, username: str, password: str) -> None:
    sdir = _user_secrets_dir(stick, username)
    sdir.mkdir(parents=True, exist_ok=True)

    pwd_file = sdir / "password"
    pwd_file.write_text(password + "\n")
    os.chmod(pwd_file, stat.S_IRUSR | stat.S_IWUSR)  # 0600

    print("[...] Hashing password (sha512crypt)…", file=sys.stderr)
    hashed = _hash_password(password)
    hash_file = sdir / "password.hash"
    hash_file.write_text(hashed + "\n")
    # hash is safe to read by others; 0644
    os.chmod(hash_file, stat.S_IRUSR | stat.S_IWUSR | stat.S_IRGRP | stat.S_IROTH)


