def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    fn = DISPATCH.get((args.command, args.subcommand))
    if fn is None:
        parser.print_help()
        sys.exit(1)
    fn(args)


if __name__ == "__main__":
    main()
