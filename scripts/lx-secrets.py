def cmd_admin_import_snippet(args) -> None:
    """
    Import a user's submitted YAML snippet onto the admin stick.

    The snippet format is the output of 'user sync': an 'authentication'
    dict with pubkeys and password hashes.  Plaintext passwords are not
    accepted here — they would be rejected.

    Only the pubkey and password_hash fields are imported.
    """
    stick = require_stick(args)
    _require_admin_stick(stick)

    snippet_path = Path(args.snippet_file)
    if not snippet_path.exists():
        print(f"[error] Snippet file not found: {snippet_path}", file=sys.stderr)
        sys.exit(1)

    data = yaml.safe_load(snippet_path.read_text()) or {}
    auth = data.get("authentication", {})
    if not auth:
        print("[error] No 'authentication' key found in snippet.", file=sys.stderr)
        sys.exit(1)

    imported = 0
    for username, entry in auth.items():
        if not isinstance(entry, dict):
            continue

        user_dir = stick / "identities" / "users" / username
        user_dir.mkdir(parents=True, exist_ok=True)

        # Import pubkeys
        for field, value in entry.items():
            if field.endswith("_pub"):
                key_name = field[:-4]  # strip _pub → id_ed25519
                pub_file = user_dir / f"{key_name}.pub"
                pub_file.write_text(value.strip() + "\n")
                os.chmod(pub_file, stat.S_IRUSR | stat.S_IWUSR | stat.S_IRGRP | stat.S_IROTH)
                print(f"[ok] {username}: imported {field}")
                imported += 1
            elif field == "password_hash":
                sdir = _user_secrets_dir(stick, username)
                sdir.mkdir(parents=True, exist_ok=True)
                hash_file = sdir / "password.hash"
                hash_file.write_text(value.strip() + "\n")
                os.chmod(hash_file, stat.S_IRUSR | stat.S_IWUSR | stat.S_IRGRP | stat.S_IROTH)
                print(f"[ok] {username}: imported password_hash")
                imported += 1
            elif field == "password":
                print(f"[skip] {username}: plaintext 'password' field rejected — import denied")

    if imported:
        print(f"\n[ok] Imported {imported} fields. Run 'identity sync-inventory' to update inventory.")
    else:
        print("[warn] Nothing was imported.")


