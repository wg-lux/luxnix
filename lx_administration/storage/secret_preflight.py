"""Prove, before erasure, that the secrets this host actually needs survive it.

The required set comes from the plan's evaluated configuration, not a fixed list:
account hashes, every key and salt generation that opens or identifies existing data,
VPN identity and keys for retained encrypted volumes. Hosts with data are migrated, so
a data key can never be waived as absent: provisioning would issue a replacement that
cannot read what exists. Material that its provisioner can regenerate or that
enrollment re-delivers is deliberately excluded, see NOT_REQUIRED.

Read-only apart from the receipt. It never copies, generates, rotates or deletes a
credential, and never prints or stores values or digests of them.
"""

from __future__ import annotations

import getpass
import hmac
import os
from pathlib import Path
import shlex
import socket
import stat
import subprocess
import sys
import time
import warnings

import yaml

from lx_administration.secret_storage import encrypted_storage
from lx_administration.storage import boot_migration as migration
from lx_administration.storage.cutover import atomic_json

NOT_REQUIRED = (
    "regenerated by managed-secrets: maintenance password, local database and "
    "service passwords",
    "re-delivered by enrollment: Vault AppRole files, node secret, hub CA and public "
    "recipient, keycloak.env",
    "derived from the admin vault: ~/.lxv/deploy",
)
# Directories holding records encrypted with the admin vault key.
VAULT_RECORD_DIRECTORIES = ("secrets", "storage-recovery", "openbao-local")
# Re-exported or transient: not worth preserving, and not expected to match.
VAULT_COPY_EXCLUDES = ("deploy", ".lock", ".export.lock")


class PreflightError(migration.MigrationError):
    pass


def root_prefix() -> list[str]:
    return [] if os.geteuid() == 0 else ["sudo"]


def privileged(*command: str) -> subprocess.CompletedProcess:
    # Diagnostics may name private paths; only the exit status is relied upon.
    return subprocess.run(
        [*root_prefix(), *command],
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        timeout=600,
        check=False,
    )


def exists(path: Path) -> bool:
    return privileged("test", "-e", str(path)).returncode == 0


def is_directory(path: Path) -> bool:
    return privileged("test", "-d", str(path)).returncode == 0


def identical(live: Path, copy: Path, *excludes: str) -> bool:
    if is_directory(live):
        options = [f"--exclude={name}" for name in excludes]
        command = ["diff", "-rq", "--no-dereference", *options]
    else:
        command = ["cmp", "-s"]
    return privileged(*command, str(live), str(copy)).returncode == 0


def read_private(path: Path) -> bytes:
    result = privileged("cat", str(path))
    if result.returncode:
        raise PreflightError(f"Cannot read {path}")
    return result.stdout


def require_target_host(plan: dict) -> None:
    """Live files are only meaningful on the machine the plan will erase."""
    if socket.gethostname().split(".", 1)[0] != plan["spec"]["host"]:
        raise PreflightError(
            f"Run preflight on {plan['spec']['host']}: it compares that machine's "
            "live files"
        )
    hardware = read_private(migration.DMI_UUID).decode().strip().lower()
    if hardware != plan["spec"]["hardware_uuid"].lower():
        raise PreflightError("This is not the hardware selected by the plan")


def require_custody_directory(custody: Path, plan: dict) -> None:
    from lx_administration.storage.recovery_custody import storage_disks

    if not custody.is_absolute() or custody.resolve() != custody:
        raise PreflightError("Custody must be an absolute path without symbolic links")
    if not custody.exists():
        raise PreflightError(
            f"Custody directory {custody} does not exist. Mount your encrypted custody "
            "first, or use the path it is mounted at"
        )
    info = custody.lstat()
    if not stat.S_ISDIR(info.st_mode) or info.st_mode & 0o077:
        raise PreflightError("Custody must be a private directory (mode 0700)")
    encrypted_storage(custody)
    selected = {os.path.realpath(d["path"]) for d in plan["spec"]["disks"]}
    if storage_disks(custody) & selected:
        raise PreflightError(
            "Custody is on a disk this plan selects; use independent encrypted media"
        )


def retained_volume_keys(plan: dict) -> list[dict]:
    """Key files for encrypted volumes that outlive this erase.

    A volume on a selected disk is recreated, so its old key is useless. A volume
    elsewhere still holds data only its existing key can open.
    """
    selected = {os.stat(d["path"]).st_rdev for d in plan["spec"]["disks"]}
    keys = []
    for line in plan["config"].get("crypttab", "").splitlines():
        fields = line.split()
        if len(fields) < 3 or line.lstrip().startswith("#"):
            continue
        name, device, key = fields[:3]
        if not key.startswith("/"):
            continue
        if os.path.exists(device) and migration.device_disks(device) <= selected:
            continue
        keys.append({"kind": "key", "id": f"luks-key-{name}", "path": key})
    return keys


def identity_generations(contract: dict, items: list[dict]) -> list[dict]:
    """Salt generations on this host, which the evaluated config cannot enumerate.

    Hosts issue their own salt and center enrollment adds generations at runtime.
    A replacement cannot recreate old hashes or open data tied to a lost generation,
    so everything present and everything the keyring references is required.
    """
    directory = contract.get("identity_directory")
    if not directory:
        return []
    listing = privileged(
        "find",
        directory,
        "-maxdepth",
        "1",
        "-type",
        "f",
        "(",
        "-name",
        "lx_annotate_identity_*",
        "-o",
        "-name",
        "lx_annotate_center_*",
        ")",
    )
    if listing.returncode and exists(Path(directory)):
        raise PreflightError(f"Cannot list salt generations in {directory}")
    paths = set(listing.stdout.decode().splitlines())
    keyring = next((i for i in items if i["id"] == "identity-salt-keyring"), None)
    if keyring and exists(Path(keyring["path"])):
        manifest = yaml.safe_load(read_private(Path(keyring["path"])))
        paths |= set(absolute_paths(manifest))
    known = {item["path"] for item in items}
    return [
        {"kind": "data", "id": f"identity-file-{Path(path).name}", "path": path}
        for path in sorted(paths - known)
    ]


def absolute_paths(value: object) -> list[str]:
    if isinstance(value, dict):
        value = list(value.values())
    if isinstance(value, list):
        return [path for entry in value for path in absolute_paths(entry)]
    return [value] if isinstance(value, str) and value.startswith("/") else []


def copy_hint(live: Path, copy: Path) -> str:
    source, target = shlex.quote(str(live)), shlex.quote(str(copy))
    if is_directory(live):
        parent = shlex.quote(str(copy.parent))
        return f"sudo mkdir -p {parent} && sudo cp -a {source} {target}"
    return f"sudo install -D -m 0600 {source} {target}"


def required_items(plan: dict, contract: dict) -> list[dict]:
    items = [*contract["items"], *retained_volume_keys(plan)]
    return items + identity_generations(contract, items)


def missing_copies(state: Path, custody: Path) -> list[tuple[Path, Path]]:
    """Secrets on this host with no custody copy; existing copies are never touched."""
    with migration.locked_state(state):
        plan = migration.load_plan(state)
        migration.verify_source(plan)
        contract = migration.secret_contract(plan)
        require_target_host(plan)
        require_custody_directory(custody, plan)
        items = required_items(plan, contract)
        host = plan["spec"]["host"]
    pairs = ((Path(i["path"]), custody_copy(custody, host, i["path"])) for i in items)
    return [(live, copy) for live, copy in pairs if exists(live) and not exists(copy)]


def copy_to_custody(live: Path, copy: Path) -> None:
    if is_directory(live):
        command = ["cp", "-a", str(live), str(copy)]
        if privileged("mkdir", "-p", str(copy.parent)).returncode:
            raise PreflightError(f"Could not create {copy.parent}")
    else:
        command = ["install", "-D", "-m", "0600", str(live), str(copy)]
    if privileged(*command).returncode:
        raise PreflightError(f"Could not copy {live} into custody")


def custody_copy(custody: Path, host: str, path: str) -> Path:
    return custody / host / "secrets" / path.lstrip("/")


def missing_salts(state: Path, custody: Path) -> list[str]:
    """Salts neither on this host nor in custody, so nothing can preserve them."""
    with migration.locked_state(state):
        plan = migration.load_plan(state)
        items = required_items(plan, migration.secret_contract(plan))
        host = plan["spec"]["host"]
    return [
        item["path"]
        for item in items
        if migration.is_salt_id(item["id"])
        and not exists(Path(item["path"]))
        and not exists(custody_copy(custody, host, item["path"]))
    ]


def orphaned_salt(state: Path, custody: Path) -> dict | None:
    """The host's salt is gone but traces remain, so its provisioner would refuse.

    A center host is left out: its active salt comes back from Vault.
    """
    with migration.locked_state(state):
        plan = migration.load_plan(state)
        contract = migration.secret_contract(plan)
        host = plan["spec"]["host"]
    by_id = {item["id"]: item["path"] for item in contract["items"]}
    active = by_id.get("identity-active")
    stores = [by_id.get("identity-salt-recovery"), contract.get("identity_replica")]
    stores = [store for store in stores if store]
    if not active or any(
        exists(Path(path))
        for path in [active, *(str(Path(s, "active.salt")) for s in stores)]
    ):
        return None
    traces = [
        path
        for path in [
            by_id.get("identity-salt-keyring"),
            by_id.get("identity-legacy-default"),
            *(str(Path(s, "enrolled")) for s in stores),
        ]
        if path and exists(Path(path))
    ]
    if not traces:
        return None
    keyring = by_id.get("identity-salt-keyring")
    manifest = yaml.safe_load(read_private(Path(keyring))) if keyring in traces else {}
    if manifest.get("center_id"):
        return None
    copy = custody_copy(custody, host, active)
    return {"active": active, "traces": traces, "copy": copy if exists(copy) else None}


def restore_salt(copy: Path, active: str) -> None:
    if privileged("install", "-D", "-m", "0600", str(copy), active).returncode:
        raise PreflightError(f"Could not restore {active} from custody")


def set_aside(paths: list[str]) -> list[str]:
    """Move traces aside, never delete them, so the provisioner may start fresh."""
    stamp = time.strftime("%Y%m%d%H%M%S")
    moved = []
    for path in paths:
        target = f"{path}.superseded-{stamp}"
        if privileged("mv", "-n", path, target).returncode:
            raise PreflightError(f"Could not set {path} aside; nothing was deleted")
        moved.append(target)
    return moved


def check_item(
    item: dict,
    custody: Path,
    host: str,
    accepted: set[str],
    *,
    keeps_data: bool,
    accept_salt_loss: bool = False,
) -> tuple[str, str | None]:
    """Return the item's status and, when a copy is missing, how to make it."""
    from lx_administration.storage.operator_migration import (
        MigrationError as AccountError,
        validate_account_hash,
    )

    live = Path(item["path"])
    copy = custody_copy(custody, host, item["path"])
    on_host = exists(live)
    # A salt that still exists is always copied; only one already gone can be accepted.
    salt = migration.is_salt_id(item["id"])
    if accept_salt_loss and salt and not on_host and not exists(copy):
        return "accepted-loss", None
    # A locked container looks exactly like a missing file, so absence is never
    # assumed: the operator must state it, per item, after checking.
    if not on_host and item["id"] not in accepted:
        return "absent-on-host", None
    if not exists(copy):
        if not on_host and item["kind"] == "data" and keeps_data:
            # Provisioning would issue a new key, silently orphaning existing data.
            return "data-key-absent", None
        if not on_host and item["kind"] != "account":
            return "accepted-absent", None
        return "not-in-custody", copy_hint(live, copy) if on_host else None
    if on_host and not identical(live, copy):
        return "differs", copy_hint(live, copy)
    if item["kind"] == "account":
        try:
            validate_account_hash(read_private(copy))
        except AccountError:
            return "invalid-hash", None
    return "verified", None


def check_controller(
    plan: dict, custody: Path, key_custody: Path | None
) -> tuple[dict, list[str]]:
    """Require the admin vault and its key separately, if they live on this host."""
    from lx_administration.models.vault.secret import decrypt_secret
    from lx_administration.storage.recovery_custody import (
        CustodyError,
        independent,
        private,
    )

    home = Path("/home") / plan["config"]["admin"]["name"]
    vault, key = home / ".lxv", home / ".lxv.key"
    if not exists(vault) and not exists(key):
        return {"present": False, "records_decrypted": 0}, []
    copy = custody / "controller" / ".lxv"
    excludes = " ".join(f"--exclude={name}" for name in VAULT_COPY_EXCLUDES)
    target = shlex.quote(str(copy))
    hint = (
        f"sudo mkdir -p {target} && "
        f"sudo rsync -a {excludes} {shlex.quote(str(vault))}/ {target}/"
    )
    if key_custody is None:
        return {"present": True, "records_decrypted": 0}, [
            "this host holds the admin vault: pass --vault-key-custody <file>, a "
            "private copy you own on encrypted media separate from --custody"
        ]
    try:
        private(key_custody)
        independent(key_custody, custody)
    except (CustodyError, OSError) as error:
        return {"present": True, "records_decrypted": 0}, [f"vault key copy: {error}"]
    problems = []
    if not identical(key, key_custody):
        problems.append("vault key copy differs from the live key")
    if not exists(copy):
        problems.append(f"admin vault is not in custody; make the copy: {hint}")
    elif not identical(vault, copy, *VAULT_COPY_EXCLUDES):
        problems.append(f"admin vault copy differs; refresh it: {hint}")
    decrypted = 0
    if not problems:
        # Proves the copied key opens the copied records, without using this disk.
        for directory in VAULT_RECORD_DIRECTORIES:
            for record in sorted((copy / directory).rglob("*")):
                if not record.is_file() or not record.read_bytes().startswith(
                    b"$ANSIBLE_VAULT"
                ):
                    continue
                try:
                    decrypt_secret(record, key_custody)
                except (ValueError, OSError):
                    problems.append(f"cannot decrypt {record} with the vault key copy")
                else:
                    decrypted += 1
        if not decrypted and not problems:
            problems.append("no admin vault records were found to test")
    return {"present": True, "records_decrypted": decrypted}, problems


def verify_admin_password(hashed: bytes) -> None:
    """Catch the lockout a format check cannot: a valid hash nobody can log in with."""
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", DeprecationWarning)
        import crypt

    if not sys.stdin.isatty():
        raise PreflightError("Testing the admin password needs a private terminal")
    expected = hashed.decode().strip()
    password = getpass.getpass("Admin password for this host (checked, not stored): ")
    computed = crypt.crypt(password, expected)
    del password
    if not computed or not hmac.compare_digest(computed, expected):
        raise PreflightError(
            "That password does not match the preserved admin hash. Installing this "
            "hash would lock you out; do not continue"
        )


def run(
    state: Path,
    custody: Path,
    *,
    key_custody: Path | None = None,
    accept_absent: tuple[str, ...] = (),
    salt_loss_accepted_by: str | None = None,
) -> dict:
    with migration.locked_state(state):
        plan = migration.load_plan(state)
        migration.verify_source(plan)
        contract = migration.secret_contract(plan)
        if contract["vault_server"] or contract["openbao"]:
            raise PreflightError(
                "This host runs a secrets server whose data and unseal material "
                "preflight cannot verify; follow docs/vault-server-rebuild.md"
            )
        # A failed rerun must not leave an earlier success standing.
        receipt_path = state / migration.PREFLIGHT_RECEIPT
        receipt_path.unlink(missing_ok=True)
        require_target_host(plan)
        require_custody_directory(custody, plan)
        items = required_items(plan, contract)
        keeps_data = plan["spec"].get("installation", "migration") in {
            "migration",
            "in-place",
        }
        if not keeps_data:
            print(
                f"WARNING: this plan is '{plan['spec']['installation']}' and does "
                "not keep data. Use installation: in-place for a host with data."
            )
        accepted = set(accept_absent)
        unknown = accepted - {item["id"] for item in items}
        if unknown:
            raise PreflightError(
                f"Not required on this host: {', '.join(sorted(unknown))}"
            )
        host = plan["spec"]["host"]
        print(f"Secrets {host} needs, in {custody}/{host}/secrets:")
        results, hints = [], []
        for item in items:
            status, hint = check_item(
                item,
                custody,
                host,
                accepted,
                keeps_data=keeps_data,
                accept_salt_loss=salt_loss_accepted_by is not None,
            )
            results.append({"id": item["id"], "path": item["path"], "status": status})
            print(f"  {status:16} {item['id']}  {item['path']}")
            if hint:
                hints.append(hint)
            if status == "absent-on-host":
                waiver = (
                    "If it was never enrolled, --accept-salt-loss states that records "
                    "imported so far may be lost."
                    if migration.is_salt_id(item["id"])
                    else "This plan keeps data, so it cannot be waived: restore it."
                    if item["kind"] == "data" and keeps_data
                    else f"If it never existed here, pass --accept-absent {item['id']}"
                )
                hints.append(
                    f"# {item['path']} is not on this host. If a locked container "
                    f"hides it, unlock it first. {waiver}"
                )
        controller, problems = check_controller(plan, custody, key_custody)
        problems.extend(
            f"{r['id']}: {r['status']}"
            for r in results
            if r["status"] not in migration.PREFLIGHT_PASSING
        )
        print("Not required:")
        for reason in NOT_REQUIRED:
            print(f"  {reason}")
        if problems:
            for line in hints:
                print(line)
            raise PreflightError(
                "Secrets are not safe yet; no receipt was written:\n  "
                + "\n  ".join(problems)
            )
        admin = next(i for i in items if i["id"] == "admin-password-hash")
        copy = custody_copy(custody, host, admin["path"])
        verify_admin_password(read_private(copy))
        receipt = {
            "schema_version": 1,
            "kind": "secret-preflight",
            "plan_id": plan["plan_id"],
            "host": host,
            "recorded_at": time.time(),
            "custody": str(custody),
            "items": results,
            "controller": controller,
            "admin_password_verified": True,
        }
        if any(r["status"] == "accepted-loss" for r in results):
            receipt["salt_loss_accepted_by"] = salt_loss_accepted_by
        atomic_json(receipt_path, receipt)
        print(
            f"\nSUCCESS: Preflight passed; {len(results)} secrets match their custody "
            f"copies. Receipt: {receipt_path} (valid for 24 hours)."
        )
        return receipt
