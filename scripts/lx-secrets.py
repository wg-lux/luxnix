        print(f"\n  OpenVPN:")
        for label, path in checks.items():
            status = "[ok]" if path.exists() else "[missing]"
            print(f"    {label:<12}: {status}")
        if clients:
            names = ", ".join(c.name for c in clients)
            print(f"    Clients     : {names}")


