def _user_key_path(stick: Path, username: str, key_type: str) -> Path:
    return stick / "identities" / "users" / username / f"id_{key_type}"


def _host_key_path(stick: Path, hostname: str, key_type: str) -> Path:
    return stick / "identities" / "hosts" / hostname / f"ssh_host_{key_type}_key"


def _generate_keypair(
    private_path: Path, key_type: str, comment: str, force: bool
) -> tuple[Path, Path]:
    pub_path = Path(str(private_path) + ".pub")

    if private_path.exists() and not force:
        raise FileExistsError(
            f"Key already exists: {private_path}\n  Pass --force to overwrite."
        )
    if private_path.exists():
        private_path.unlink()
        pub_path.unlink(missing_ok=True)

    private_path.parent.mkdir(parents=True, exist_ok=True)

    result = subprocess.run(
        ["ssh-keygen", "-t", key_type, "-f", str(private_path), "-N", "", "-C", comment],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        print(result.stderr, file=sys.stderr)
        sys.exit(result.returncode)

    os.chmod(private_path, stat.S_IRUSR | stat.S_IWUSR)
    os.chmod(pub_path, stat.S_IRUSR | stat.S_IWUSR | stat.S_IRGRP | stat.S_IROTH)
    return private_path, pub_path


def _print_identities(stick: Path) -> None:
    users_dir = stick / "identities" / "users"
    hosts_dir = stick / "identities" / "hosts"

    if users_dir.is_dir():
        users = sorted(users_dir.iterdir())
        if users:
            print(f"\n  User identities ({len(users)}):")
            for u in users:
                pub = next(u.glob("*.pub"), None)
                has_pwd = (u / "secrets" / "password").exists()
                has_hash = (u / "secrets" / "password.hash").exists()
                key_label = pub.stem.replace("id_", "") if pub else "?"
                short = pub.read_text().strip()[:68] if pub else "(no public key)"
                pwd_tag = " [pwd]" if has_pwd else (" [hash]" if has_hash else "")
                print(f"    {u.name} [{key_label}]{pwd_tag}: {short}…")

    if hosts_dir.is_dir():
        hosts = sorted(hosts_dir.iterdir())
        if hosts:
            print(f"\n  Host identities ({len(hosts)}):")
            for h in hosts:
                pub = next(h.glob("*.pub"), None)
                if pub:
                    short = pub.read_text().strip()[:68]
                    print(f"    {h.name}: {short}…")
                else:
                    print(f"    {h.name}: (no public key)")


