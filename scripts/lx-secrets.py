#!/usr/bin/env python3
"""
lx-secrets — Secrets stick management CLI.

The secrets stick is the root of trust for the LX infrastructure.  It is a
USB device with a well-known directory layout that holds SSH identities,
certificates, and (optionally) user passwords.

Two stick modes:
  admin  — Full network administration: all identities, all certs, can stage
           secrets for Ansible deployment, can import user submissions.
  user   — Personal stick for one user: their SSH key and password only.
           Syncs only public/hashed data to the inventory (no plaintext).

Usage:
    lx-secrets <command> <subcommand> [options]

Commands:
    stick check / init / backup

    identity list
    identity gen-user NAME       Generate a user SSH key-pair on the stick
    identity gen-host NAME       Generate a host SSH key-pair on the stick
    identity import-keypair      Import an existing user key pair (synced to inventory)
    identity import-infra-key    Import an infra key (e.g. Hetzner bootstrap; NOT synced)
    identity sync-inventory      Write pubkeys + password hashes to stick_pubkeys.yml
                                 (safe to commit; no plaintext passwords)

    user set-password       Set or generate a password for a user
    user show-hash          Print the stored password hash (safe)
    user show-password      Print the plaintext password (stick owner only /
                            admin-mode only for other users)
    user sync               Output a YAML snippet for submitting to the admin
                            (personal sticks: own data only)

    admin import-snippet    Import a user's submitted YAML snippet onto the
                            admin stick (pubkey + hash only)
    admin import-pubkey     Import a single pubkey onto the admin stick
    admin list-users        List all users with their data status

    cert list / import-ssl / import-openvpn / deploy-ssl / deploy-openvpn

    vault stage-ssl              Stage SSL cert into ~/.lxv/deploy/<hostname>/
    vault stage-ssl-group        Stage SSL cert for all hosts in an inventory group
    vault stage-keycloak-admin   Stage keycloak_admin bootstrap password for a host
    vault stage-passwords        Write admin-passwords.yml from stick for vault bootstrap
    vault status                 Show staged files per hostname

Stick directory layout (admin mode):
    <stick>/
    ├── .stick-meta.yml                 # mode, uuid, created, version
    ├── identities/
    │   ├── users/
    │   │   └── <username>/
    │   │       ├── id_ed25519[.pub]    # SSH keypair
    │   │       └── secrets/
    │   │           ├── password        # plaintext  (mode 0600, NEVER sync)
    │   │           └── password.hash   # sha512crypt (mode 0644, safe to sync)
    │   ├── infra/
    │   │   └── <name>/
    │   │       └── id_<type>[.pub]     # Infra key (e.g. Hetzner bootstrap; NOT synced)
    │   └── hosts/
    │       └── <hostname>/ssh_host_ed25519_key[.pub]
    ├── certificates/
    │   ├── ssl/<domain>/fullchain.pem + privkey.pem
    │   └── openvpn/
    │       ├── ca/ca.pem + ca.key
    │       ├── server/crt.crt + key.key + dh.pem
    │       ├── tls.pem
    │       └── clients/<hostname>/crt.crt + key.key
    └── backups/<timestamp>.tar.gz

Personal stick layout (user mode):
    <stick>/
    ├── .stick-meta.yml                 # mode: user, owner: <username>
    └── identities/
        └── users/
            └── <owner>/
                ├── id_ed25519[.pub]
                └── secrets/
                    ├── password
                    └── password.hash
"""

