def cmd_identity_gen_user(args) -> None:
    stick = require_stick(args)

    # On a user-mode stick: only the owner can generate keys
    mode = _stick_mode(stick)
    owner = _stick_owner(stick)
    if mode == "user" and owner and args.username != owner:
        print(
            f"[error] Personal stick (owner: {owner}) — "
            f"cannot generate keys for '{args.username}'.",
            file=sys.stderr,
        )
        sys.exit(1)

    key_type: str = args.key_type
    username: str = args.username
    priv = _user_key_path(stick, username, key_type)

    try:
        priv, pub = _generate_keypair(priv, key_type, f"{username}@lx-secrets", args.force)
    except FileExistsError as e:
        print(f"[error] {e}", file=sys.stderr)
        sys.exit(1)

    print(f"[ok] Generated {key_type} key for user '{username}'")
    print(f"     Private : {priv}")
    print(f"     Public  : {pub}")
    print(f"     Pubkey  : {pub.read_text().strip()}")


def cmd_identity_gen_host(args) -> None:
    stick = require_stick(args)
    _require_admin_stick(stick)

    key_type: str = args.key_type
    hostname: str = args.hostname
    priv = _host_key_path(stick, hostname, key_type)

    try:
        priv, pub = _generate_keypair(priv, key_type, f"{hostname}@lx-secrets", args.force)
    except FileExistsError as e:
        print(f"[error] {e}", file=sys.stderr)
        sys.exit(1)

    print(f"[ok] Generated {key_type} host key for '{hostname}'")
    print(f"     Private : {priv}")
    print(f"     Public  : {pub}")
    print(f"     Pubkey  : {pub.read_text().strip()}")


def cmd_identity_import_keypair(args) -> None:
    """
    Import an existing SSH key pair into the vault.

    Copies both the private key (0600) and public key (0644) into
    <stick>/identities/users/<username>/id_<type>[.pub].

    Use --deploy-local to also install the private key at ~/.ssh/id_<type>.
    """
    stick = require_stick(args)

    username: str = args.username
    priv_src = Path(args.private_key).expanduser()
    pub_src_arg: Optional[str] = getattr(args, "public_key", None)
    pub_src = Path(pub_src_arg).expanduser() if pub_src_arg else None

    if not priv_src.exists():
        print(f"[error] Private key not found: {priv_src}", file=sys.stderr)
        sys.exit(1)

    # Auto-detect public key if not given
    if pub_src is None:
        candidate = Path(str(priv_src) + ".pub")
        if candidate.exists():
            pub_src = candidate
        else:
            print(
                f"[error] Public key not found. Pass --public <path> or place "
                f"<private>.pub alongside the private key.",
                file=sys.stderr,
            )
            sys.exit(1)

    if not pub_src.exists():
        print(f"[error] Public key not found: {pub_src}", file=sys.stderr)
        sys.exit(1)

    # Validate public key format
    pubkey_text = pub_src.read_text().strip()
    parts = pubkey_text.split()
    if len(parts) < 2 or not parts[0].startswith("ssh-"):
        print(f"[error] Invalid public key format in {pub_src}", file=sys.stderr)
        sys.exit(1)
    key_type = parts[0].replace("ssh-", "")  # ed25519, rsa, etc.

    user_dir = stick / "identities" / "users" / username
    priv_dest = user_dir / f"id_{key_type}"
    pub_dest = user_dir / f"id_{key_type}.pub"

    if priv_dest.exists() and not args.force:
        print(
            f"[error] Key already exists at {priv_dest}.\n"
            f"  Use --force to overwrite.",
            file=sys.stderr,
        )
        sys.exit(1)

    user_dir.mkdir(parents=True, exist_ok=True)

    _secure_copy(priv_src, priv_dest, stat.S_IRUSR | stat.S_IWUSR)
    _secure_copy(
        pub_src, pub_dest,
        stat.S_IRUSR | stat.S_IWUSR | stat.S_IRGRP | stat.S_IROTH,
    )

    print(f"[ok] Imported {key_type} key pair for '{username}'")
    print(f"     Private : {priv_dest}")
    print(f"     Public  : {pub_dest}")
    print(f"     Pubkey  : {pubkey_text[:80]}{'...' if len(pubkey_text) > 80 else ''}")

    if args.deploy_local:
        local_priv = Path.home() / ".ssh" / f"id_{key_type}"
        if local_priv.exists() and not args.force:
            print(
                f"[warn] {local_priv} already exists — skipping local deploy.\n"
                f"  Use --force to overwrite."
            )
        else:
            _secure_copy(priv_dest, local_priv, stat.S_IRUSR | stat.S_IWUSR)
            print(f"[ok] Deployed private key to {local_priv}")
    else:
        print(f"\nTo deploy the private key locally:")
        print(f"  cp {priv_dest} ~/.ssh/id_{key_type}")
        print(f"  chmod 600 ~/.ssh/id_{key_type}")

    print(f"\nNext: sync public key to Ansible inventory and regenerate NixOS configs:")
    print(f"  python3 scripts/lx-secrets.py identity sync-inventory")
    print(f"  devenv tasks run autoconf:finished")


def cmd_identity_import_infra_key(args) -> None:
    """
    Import an infrastructure SSH key (e.g. Hetzner bootstrap key) into the vault.

    Stored under <stick>/identities/infra/<name>/id_<type>[.pub].
    This path is intentionally separate from identities/users/ so that
    sync-inventory does NOT push this key to stick_pubkeys.yml or any
    machine's authorized_keys.

    Use --deploy-path to install the private key at a custom local path
    (e.g. ~/.ssh/ssh-hetzner-main_openssh) rather than ~/.ssh/id_<type>.
    """
    stick = require_stick(args)

    name: str = args.name
    priv_src = Path(args.private_key).expanduser()
    pub_src_arg: Optional[str] = getattr(args, "public_key", None)
    pub_src = Path(pub_src_arg).expanduser() if pub_src_arg else None
    deploy_path_arg: Optional[str] = getattr(args, "deploy_path", None)

    if not priv_src.exists():
        print(f"[error] Private key not found: {priv_src}", file=sys.stderr)
        sys.exit(1)

    # Auto-detect public key if not given
    if pub_src is None:
        candidate = Path(str(priv_src) + ".pub")
        if candidate.exists():
            pub_src = candidate
        else:
            print(
                f"[error] Public key not found. Pass --public <path> or place "
                f"<private>.pub alongside the private key.",
                file=sys.stderr,
            )
            sys.exit(1)

    if not pub_src.exists():
        print(f"[error] Public key not found: {pub_src}", file=sys.stderr)
        sys.exit(1)

    # Validate public key format
    pubkey_text = pub_src.read_text().strip()
    parts = pubkey_text.split()
    if len(parts) < 2 or not parts[0].startswith("ssh-"):
        print(f"[error] Invalid public key format in {pub_src}", file=sys.stderr)
        sys.exit(1)
    key_type = parts[0].replace("ssh-", "")  # ed25519, rsa, etc.

    infra_dir = stick / "identities" / "infra" / name
    priv_dest = infra_dir / f"id_{key_type}"
    pub_dest = infra_dir / f"id_{key_type}.pub"

    if priv_dest.exists() and not args.force:
        print(
            f"[error] Key already exists at {priv_dest}.\n"
            f"  Use --force to overwrite.",
            file=sys.stderr,
        )
        sys.exit(1)

    infra_dir.mkdir(parents=True, exist_ok=True)

    _secure_copy(priv_src, priv_dest, stat.S_IRUSR | stat.S_IWUSR)
    _secure_copy(
        pub_src, pub_dest,
        stat.S_IRUSR | stat.S_IWUSR | stat.S_IRGRP | stat.S_IROTH,
    )

    print(f"[ok] Imported {key_type} infra key '{name}'")
    print(f"     Private : {priv_dest}")
    print(f"     Public  : {pub_dest}")
    print(f"     Pubkey  : {pubkey_text[:80]}{'...' if len(pubkey_text) > 80 else ''}")

    if deploy_path_arg:
        local_priv = Path(deploy_path_arg).expanduser()
        if local_priv.exists() and not args.force:
            print(
                f"[warn] {local_priv} already exists — skipping local deploy.\n"
                f"  Use --force to overwrite."
            )
        else:
            local_priv.parent.mkdir(parents=True, exist_ok=True)
            _secure_copy(priv_dest, local_priv, stat.S_IRUSR | stat.S_IWUSR)
            print(f"[ok] Deployed private key to {local_priv}")
    else:
        print(f"\nTo deploy the private key locally:")
        print(f"  cp {priv_dest} ~/.ssh/id_{key_type}")
        print(f"  chmod 600 ~/.ssh/id_{key_type}")

    print(f"\nNote: this key is stored under identities/infra/ and is NOT synced")
    print(f"to stick_pubkeys.yml or any machine's authorized_keys.")


def cmd_identity_sync_inventory(args) -> None:
    """
    Write public keys AND password hashes from the stick to
    ansible/inventory/group_vars/stick_pubkeys.yml.

    Both pubkeys and SHA-512 hashes are safe to commit to git.
    Plaintext passwords are NEVER written here.

    On a user-mode stick: only the owner's data is written.
    On an admin stick: all users are written.
    """
    stick = require_stick(args)
    out_file = Path(args.output)
    mode = _stick_mode(stick)
    owner = _stick_owner(stick)

    authentication: dict = {}

    users_dir = stick / "identities" / "users"
    if users_dir.is_dir():
        for user_dir in sorted(users_dir.iterdir()):
            if not user_dir.is_dir():
                continue
            username = user_dir.name

            # User-mode stick: only emit own data
            if mode == "user" and owner and username != owner:
                continue

            entry: dict = {}
            for pub_file in sorted(user_dir.glob("*.pub")):
                key_name = pub_file.stem  # e.g. id_ed25519
                entry[f"{key_name}_pub"] = pub_file.read_text().strip()

            hash_val = _get_user_hash(stick, username)
            if hash_val and not getattr(args, "no_hashes", False):
                entry["password_hash"] = hash_val

            if entry:
                authentication[username] = entry

    if not authentication:
        print("[warn] No user data found on stick — nothing to sync.")
        return

    output = (
        "# AUTO-GENERATED by: lx-secrets identity sync-inventory\n"
        "# DO NOT EDIT — regenerate with: devenv tasks run secrets:sync-inventory\n"
        "---\n"
    )
    output += yaml.dump(
        {"authentication": authentication},
        default_flow_style=False,
        allow_unicode=True,
        sort_keys=True,
        width=4096,
    )

    if getattr(args, "dry_run", False):
        print("[dry-run] Would write:")
        print(output)
        return

    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(output)
    print(f"[ok] Wrote {len(authentication)} identities to {out_file}")
    for name, entry in sorted(authentication.items()):
        tags = []
        for k in entry:
            if k.endswith("_pub"):
                tags.append(k)
            elif k == "password_hash":
                tags.append("hash")
        print(f"     {name}: {', '.join(tags)}")


