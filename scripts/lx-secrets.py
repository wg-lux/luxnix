def _find_stick() -> Optional[Path]:
    """Locate the secrets stick automatically."""
    env = os.environ.get(ENV_VAR)
    if env:
        p = Path(env)
        if (p / STICK_META_FILENAME).exists():
            return p
        print(
            f"[warn] {ENV_VAR}={env} is set but {STICK_META_FILENAME} was not found there.",
            file=sys.stderr,
        )

    for base in ["/run/media/admin", "/run/media", "/media", "/mnt"]:
        base_path = Path(base)
        if not base_path.is_dir():
            continue
        for candidate in sorted(base_path.iterdir()):
            if candidate.is_dir() and (candidate / STICK_META_FILENAME).exists():
                return candidate

    return None


def require_stick(args) -> Path:
    """Return the stick path or exit with an informative error."""
    if getattr(args, "stick", None):
        p = Path(args.stick)
        if not p.exists():
            print(f"[error] Stick path does not exist: {p}", file=sys.stderr)
            sys.exit(1)
        return p

    p = _find_stick()
    if p is None:
        print(
            f"[error] Secrets stick not found.\n"
            f"  Mount the stick and either:\n"
            f"    export {ENV_VAR}=/path/to/stick\n"
            f"  or pass --stick /path/to/stick",
            file=sys.stderr,
        )
        sys.exit(1)
    return p


