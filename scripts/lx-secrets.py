def cmd_stick_check(args) -> None:
    stick = require_stick(args)
    meta = _read_meta(stick)
    mode = meta.get("mode", "admin")
    owner = meta.get("owner", "")
    print(f"[ok] Stick found at {stick}")
    print(f"     UUID   : {meta.get('uuid', '?')}")
    print(f"     Mode   : {mode}" + (f"  (owner: {owner})" if owner else ""))
    print(f"     Created: {meta.get('created', '?')}")
    print(f"     Version: {meta.get('version', '?')}")

    layout = STICK_LAYOUT_USER if mode == "user" else STICK_LAYOUT_ADMIN
    missing = [d for d in layout if not (stick / d).is_dir()]
    if missing:
        print(f"[warn] Missing directories: {', '.join(missing)}")
        print(f"       Run 'lx-secrets stick init' to create them.")
    else:
        print("[ok] Directory layout is complete")

    _print_identities(stick)
    if mode == "admin":
        _print_certs(stick)


def cmd_stick_init(args) -> None:
    if getattr(args, "stick", None):
        stick = Path(args.stick)
    else:
        raw = input("Stick mount path: ").strip()
        if not raw:
            print("[error] No path provided.", file=sys.stderr)
            sys.exit(1)
        stick = Path(raw)

    if not stick.exists():
        print(f"[error] Path does not exist: {stick}", file=sys.stderr)
        sys.exit(1)

    if (stick / STICK_META_FILENAME).exists() and not getattr(args, "force", False):
        print(
            f"[error] Stick already initialised at {stick}.\n"
            f"  Pass --force to reinitialise.",
            file=sys.stderr,
        )
        sys.exit(1)

    mode = getattr(args, "mode", "admin") or "admin"
    owner = getattr(args, "owner", None)

    if mode == "user" and not owner:
        print("[error] --owner <username> is required for user-mode sticks.", file=sys.stderr)
        sys.exit(1)

    layout = STICK_LAYOUT_USER if mode == "user" else STICK_LAYOUT_ADMIN
    for d in layout:
        (stick / d).mkdir(parents=True, exist_ok=True)

    meta: dict = {
        "uuid": str(uuid.uuid4()),
        "created": datetime.now().isoformat(),
        "version": STICK_META_VERSION,
        "mode": mode,
    }
    if owner:
        meta["owner"] = owner
        meta["description"] = f"LX personal secrets stick for {owner}"
    else:
        meta["description"] = "LX admin secrets stick"

    _write_meta(stick, meta)
    print(f"[ok] Stick initialised at {stick}  (mode: {mode})")
    if owner:
        print(f"     Owner: {owner}")
    print(f"     UUID : {meta['uuid']}")
    print()
    if mode == "user":
        print(f"Next steps:")
        print(f"  export {ENV_VAR}={stick}")
        print(f"  lx-secrets identity gen-user {owner}")
        print(f"  lx-secrets user set-password --username {owner} --generate")
        print(f"  lx-secrets user sync --output my-pubkey-{owner}.yml")
        print(f"  # Submit my-pubkey-{owner}.yml as a PR for the admin to import")
    else:
        print(f"Next steps:")
        print(f"  export {ENV_VAR}={stick}")
        print(f"  lx-secrets identity gen-user admin")
        print(f"  lx-secrets cert import-openvpn /etc/openvpn")


def cmd_stick_backup(args) -> None:
    stick = require_stick(args)
    backup_dir = stick / "backups"
    backup_dir.mkdir(exist_ok=True)

    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_file = backup_dir / f"backup_{ts}.tar.gz"

    with tarfile.open(backup_file, "w:gz") as tar:
        for item in sorted(stick.iterdir()):
            if item.name == "backups":
                continue
            tar.add(item, arcname=item.name)

    os.chmod(backup_file, stat.S_IRUSR | stat.S_IWUSR)
    size_kb = backup_file.stat().st_size / 1024
    print(f"[ok] Backup created: {backup_file.name}  ({size_kb:.1f} KB)")

    existing = sorted(backup_dir.glob("backup_*.tar.gz"))
    for old in existing[:-5]:
        old.unlink()
        print(f"[ok] Pruned old backup: {old.name}")


